// Wraps js-aruco2's script-style sources (cv.js + aruco.js) into one ES module,
// so the detector worker can import it without CommonJS / `this` tricks.
import { readFileSync, writeFileSync, mkdirSync } from 'node:fs';
import { createRequire } from 'node:module';
import { dirname, join } from 'node:path';

const require = createRequire(import.meta.url);
const srcDir = dirname(require.resolve('js-aruco2'));
const cv = readFileSync(join(srcDir, 'cv.js'), 'utf8');
const aruco = readFileSync(join(srcDir, 'aruco.js'), 'utf8');
const license = readFileSync(join(srcDir, '..', 'LICENSE.txt'), 'utf8');

const out = `/* AUTO-GENERATED by scripts/vendor-aruco.mjs from js-aruco2 — do not edit.
${license.replace(/\*\//g, '* /')}
*/
const scope = {};
(function () {
${cv}
}).call(scope);
(function () {
const require = () => { throw new Error('require() not available'); };
${aruco}
}).call(scope);
export const CV = scope.CV;
export const AR = scope.AR;
`;
const dest = new URL('../src/vendor/aruco.js', import.meta.url);
mkdirSync(new URL('.', dest), { recursive: true });
writeFileSync(dest, out);
console.log('wrote src/vendor/aruco.js');
